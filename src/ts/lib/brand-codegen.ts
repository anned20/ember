/**
 * Renders the brand values into the generated shell module the shipped scripts
 * read. Pure string building, shared by scripts/generate-brand.ts (which writes
 * the file) and test/brand.test.ts (which fails when the committed file drifts
 * from src/ts/lib/brand.ts).
 */
import type {Brand} from './brand.js';

const GENERATED_BY = 'scripts/generate-brand.ts from src/ts/lib/brand.ts';

/** A shell single-quoted string. */
function sh(value: string): string {
  return "'" + value.replace(/'/g, "'\\''") + "'";
}

interface Row {
  shell: string;
  value: string;
}

function rows(brand: Brand): Row[] {
  return [
    {shell: 'BRAND_NAME', value: brand.name},
    {shell: 'BRAND_TAGLINE', value: brand.tagline},
    {shell: 'BRAND_VENDOR', value: brand.vendor},
    {shell: 'APP_ID', value: brand.appId},
    {shell: 'BRAND_SLUG', value: brand.slug},
    {shell: 'APPS_DIR', value: brand.appsDir},
    {shell: 'APP_DIR', value: brand.appDir},
    {shell: 'CONFIG_DIR', value: brand.configDir},
    {shell: 'INITD_DIR', value: brand.initdDir},
    {shell: 'TMP_PREFIX', value: brand.tmpPrefix},
    {shell: 'BACKUP_KIND', value: brand.backupKind},
    {shell: 'FILE_MARK', value: brand.fileMark},
    {shell: 'USB_FOLDER', value: brand.usbFolder},
    {shell: 'USB_SETTINGS_FILE', value: brand.usbSettingsFile},
    {shell: 'HOOK_HOME_WATCHER', value: brand.hooks.homeWatcher},
    {shell: 'HOOK_VOICE', value: brand.hooks.voice},
    {shell: 'HOOK_BOOT', value: brand.hooks.boot},
    {shell: 'LEGACY_HOOKS', value: brand.legacy.hooks.join(' ')},
    {shell: 'LEGACY_TMP_PREFIXES', value: brand.legacy.tmpPrefixes.join(' ')}
  ];
}

/** The contents of scripts/brand.sh. */
export function renderBrandShell(brand: Brand): string {
  const body = rows(brand).map(function (row) {
    return row.shell + '=' + sh(row.value);
  }).join('\n');
  return '# Generated by ' + GENERATED_BY + ' — do not edit; run `npm run brand`.\n' +
    '# shellcheck shell=sh\n' +
    body + '\n';
}
