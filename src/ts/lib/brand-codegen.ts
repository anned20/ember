/**
 * Renders the brand values into the generated shell and Python modules the
 * shipped scripts and the voice daemon read. Pure string building, shared by
 * scripts/generate-brand.ts (which writes the files) and test/brand.test.ts
 * (which fails when the committed files drift from src/ts/lib/brand.ts).
 */
import type {Brand} from './brand.js';

export const BRAND_SHELL_PATH = 'scripts/brand.sh';
export const BRAND_PYTHON_PATH = 'voice/daemon/brand.py';

const GENERATED_BY = 'scripts/generate-brand.ts from src/ts/lib/brand.ts';

/** A shell single-quoted string. */
function sh(value: string): string {
  return "'" + value.replace(/'/g, "'\\''") + "'";
}

/** A Python double-quoted string. */
function py(value: string): string {
  return '"' + value.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

interface Row {
  shell: string;
  python: string;
  value: string;
}

function rows(brand: Brand): Row[] {
  return [
    {shell: 'BRAND_NAME', python: 'NAME', value: brand.name},
    {shell: 'BRAND_VOICE_NAME', python: 'VOICE_NAME', value: brand.voiceName},
    {shell: 'BRAND_TAGLINE', python: 'TAGLINE', value: brand.tagline},
    {shell: 'BRAND_VOICE_TAGLINE', python: 'VOICE_TAGLINE', value: brand.voiceTagline},
    {shell: 'BRAND_VENDOR', python: 'VENDOR', value: brand.vendor},
    {shell: 'APP_ID', python: 'APP_ID', value: brand.appId},
    {shell: 'VOICE_APP_ID', python: 'VOICE_APP_ID', value: brand.voiceAppId},
    {shell: 'BRAND_SLUG', python: 'SLUG', value: brand.slug},
    {shell: 'APPS_DIR', python: 'APPS_DIR', value: brand.appsDir},
    {shell: 'APP_DIR', python: 'APP_DIR', value: brand.appDir},
    {shell: 'VOICE_CARD_DIR', python: 'VOICE_CARD_DIR', value: brand.voiceCardDir},
    {shell: 'CONFIG_DIR', python: 'CONFIG_DIR', value: brand.configDir},
    {shell: 'VOICE_CONFIG_DIR', python: 'VOICE_CONFIG_DIR', value: brand.voiceConfigDir},
    {shell: 'INITD_DIR', python: 'INITD_DIR', value: brand.initdDir},
    {shell: 'TMP_PREFIX', python: 'TMP_PREFIX', value: brand.tmpPrefix},
    {shell: 'VOICE_SOCKET', python: 'VOICE_SOCKET', value: brand.voiceSocket},
    {shell: 'VOICE_SERVICE_NAME', python: 'VOICE_SERVICE_NAME', value: brand.voiceServiceName},
    {shell: 'BACKUP_KIND', python: 'BACKUP_KIND', value: brand.backupKind},
    {shell: 'FILE_MARK', python: 'FILE_MARK', value: brand.fileMark},
    {shell: 'USB_FOLDER', python: 'USB_FOLDER', value: brand.usbFolder},
    {shell: 'USB_SETTINGS_FILE', python: 'USB_SETTINGS_FILE', value: brand.usbSettingsFile},
    {shell: 'HOOK_HOME_WATCHER', python: 'HOOK_HOME_WATCHER', value: brand.hooks.homeWatcher},
    {shell: 'HOOK_VOICE', python: 'HOOK_VOICE', value: brand.hooks.voice},
    {shell: 'HOOK_BOOT', python: 'HOOK_BOOT', value: brand.hooks.boot},
    {shell: 'LEGACY_TMP_PREFIX', python: 'LEGACY_TMP_PREFIX', value: brand.legacy.tmpPrefix},
    {shell: 'LEGACY_HOOK_HOME', python: 'LEGACY_HOOK_HOME', value: brand.legacy.homeWatcherHook},
    {shell: 'LEGACY_HOOK_BOOT', python: 'LEGACY_HOOK_BOOT', value: brand.legacy.bootHook}
  ];
}

/** The contents of scripts/brand.sh. */
export function renderBrandShell(brand: Brand): string {
  const body = rows(brand).map(function (row) {
    return row.shell + '=' + sh(row.value);
  }).join('\n');
  return '# Generated by ' + GENERATED_BY + ' — do not edit; run `npm run brand`.\n' +
    '# shellcheck shell=sh\n' +
    body + '\n';
}

/** The contents of voice/daemon/brand.py. */
export function renderBrandPython(brand: Brand): string {
  const body = rows(brand).map(function (row) {
    return row.python + ' = ' + py(row.value);
  }).join('\n');
  return '"""Generated by ' + GENERATED_BY + ' — do not edit; run `npm run brand`."""\n\n' +
    body + '\n';
}
